import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const read = (p) => readFileSync(resolve(root, p), 'utf8');

const js = read('node_modules/leaflet/dist/leaflet.js');
const css = read('node_modules/leaflet/dist/leaflet.css');

// Marker clustering. Bundled rather than loaded from a CDN so the map keeps
// working offline and gains no third-party runtime dependency.
const clusterJs = read('node_modules/leaflet.markercluster/dist/leaflet.markercluster.js');
const clusterCss =
  read('node_modules/leaflet.markercluster/dist/MarkerCluster.css') +
  '\n' +
  read('node_modules/leaflet.markercluster/dist/MarkerCluster.Default.css');

writeFileSync(
  resolve(root, 'utils/leaflet.generated.ts'),
  `// Generated by scripts/vendor-map.mjs — do not edit by hand.
// Leaflet 1.9.4, BSD-2-Clause. Leaflet.markercluster 1.5.3, MIT.
export const leafletJs = ${JSON.stringify(js)};
export const leafletCss = ${JSON.stringify(css)};
export const markerClusterJs = ${JSON.stringify(clusterJs)};
export const markerClusterCss = ${JSON.stringify(clusterCss)};
`
);
