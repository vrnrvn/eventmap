import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
const root = resolve(import.meta.dirname, '..');
const js = readFileSync(resolve(root, 'node_modules/leaflet/dist/leaflet.js'), 'utf8');
const css = readFileSync(resolve(root, 'node_modules/leaflet/dist/leaflet.css'), 'utf8');
writeFileSync(resolve(root, 'utils/leaflet.generated.ts'),
  `// Generated by scripts/vendor-map.mjs. Leaflet 1.9.4, BSD-2-Clause.\nexport const leafletJs = ${JSON.stringify(js)};\nexport const leafletCss = ${JSON.stringify(css)};\n`);
