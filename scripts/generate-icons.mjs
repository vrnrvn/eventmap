// Regenerates components/icons.generated.ts: one deep import per icon the
// app actually uses, so Metro bundles ~115 icons instead of all ~1,600 in
// lucide-react-native's barrel (Metro does not tree-shake re-exports; the
// barrel import added hundreds of KB of never-used JS to the bundle and its
// parse cost to startup).
//
// App code imports icons from '@/components/icons.generated' and never from
// 'lucide-react-native' directly. After adding a new icon name to an import,
// run:  node scripts/generate-icons.mjs
//
// Tests resolve '@/components/icons.generated' to the existing lucide stub
// (vitest.config.mts), same as they always did for the package itself.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dist = join(root, 'node_modules/lucide-react-native/dist/esm');

// ---- name -> icon file map (plain names from icons/index.js, aliases from the barrel)
const nameToFile = new Map();
const exportRe = /export\s*\{([^}]*)\}\s*from\s*'\.(?:\/icons)?\/(icons\/)?([\w-]+\.js)'/g;
const collect = (src, prefix) => {
  for (const m of src.matchAll(exportRe)) {
    const file = m[3];
    if (file === 'index.js') continue;
    for (const piece of m[1].split(',')) {
      const name = piece.trim().replace(/^default as\s+/, '');
      if (name && name !== 'default') nameToFile.set(name, prefix + file);
    }
  }
};
collect(readFileSync(join(dist, 'icons/index.js'), 'utf8'), 'icons/');
collect(readFileSync(join(dist, 'lucide-react-native.js'), 'utf8'), 'icons/');

// ---- icon names used by the app
const exts = new Set(['.ts', '.tsx']);
const used = new Set();
const importRe =
  /import\s*(?:type\s*)?\{([^}]*)\}\s*from\s*'(?:lucide-react-native|@\/components\/icons\.generated)'/gs;
const walk = (dir) => {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === 'node_modules' || entry.name.startsWith('.')) continue;
    const p = join(dir, entry.name);
    if (entry.isDirectory()) walk(p);
    else if (exts.has(entry.name.slice(entry.name.lastIndexOf('.')))) {
      const src = readFileSync(p, 'utf8');
      for (const m of src.matchAll(importRe)) {
        for (const piece of m[1].split(',')) {
          const name = piece.trim().split(/\s+as\s+/)[0].trim();
          if (name) used.add(name);
        }
      }
    }
  }
};
for (const d of ['app', 'screens', 'components', 'constants', 'hooks', 'utils']) walk(join(root, d));

const missing = [...used].filter((n) => !nameToFile.has(n));
if (missing.length) {
  console.error('Unknown lucide icon name(s):', missing.join(', '));
  process.exit(1);
}

const lines = [...used]
  .sort()
  .map((n) => `export { default as ${n} } from 'lucide-react-native/dist/esm/${nameToFile.get(n)}';`);
const header = `// AUTO-GENERATED by scripts/generate-icons.mjs — do not edit by hand.
// Deep per-icon imports: Metro bundles only these ${lines.length} icons instead of the
// whole lucide-react-native barrel (~1,600 icons). Regenerate after adding an
// icon name to any import:  node scripts/generate-icons.mjs
`;
writeFileSync(join(root, 'components/icons.generated.ts'), header + lines.join('\n') + '\n');
console.log(`components/icons.generated.ts: ${lines.length} icons`);
