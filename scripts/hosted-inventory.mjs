#!/usr/bin/env node
// Builds the hosted-database inventory SQL (docs/MIGRATIONS_PENDING.md §0,
// decision D10) with the repository's migration versions filled in, so the
// owner no longer pastes the VALUES list by hand.
//
//   node scripts/hosted-inventory.mjs            # SQL on stdout
//   node scripts/hosted-inventory.mjs > /tmp/inventory.sql
//
// READ-ONLY by construction: SELECTs only. Run it against each hosted
// project (psql, or the dashboard's SQL editor) and record the three
// answers per project under a dated heading in docs/MIGRATIONS_PENDING.md.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const dir = path.join(repo, 'supabase', 'migrations');
const versions = fs
  .readdirSync(dir)
  .filter((f) => /^\d{14}_.+\.sql$/.test(f))
  .map((f) => f.slice(0, 14))
  .sort();
if (versions.length === 0) throw new Error(`no migrations found under ${dir}`);

const SECURITY_SET = ['20261030100000', '20261030101000', '20261030102000', '20261030107000'];
const list = versions.map((v) => `  ('${v}')`).join(',\n');

console.log(`-- Hosted-database inventory (docs/MIGRATIONS_PENDING.md §0, decision D10).
-- Generated by scripts/hosted-inventory.mjs from ${versions.length} files in
-- supabase/migrations/ (${versions[0]} .. ${versions.at(-1)}).
-- Read-only: three SELECTs, nothing else.

-- 1. What is recorded
select count(*) as applied, max(version) as latest
  from supabase_migrations.schema_migrations;

-- 2. Repository files NOT recorded on this project (empty = in step with the
--    repo). Recorded versions that are not repository files are hand-applied
--    drift; find those by swapping the two sides of EXCEPT.
with files(version) as (values
${list})
select version as missing_here from files
except select version from supabase_migrations.schema_migrations
order by 1;

-- 3. The Oct 30 security set in particular (expect ${SECURITY_SET.length} rows; anything
--    missing must be applied before any feature migration).
select version from supabase_migrations.schema_migrations
 where version in (${SECURITY_SET.map((v) => `'${v}'`).join(', ')})
 order by 1;`);
